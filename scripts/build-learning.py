"""Validate reviewed instruction against the canonical registry/corpus; emit offline JS."""
import hashlib,json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
review=json.loads((ROOT/'research/movement-instruction.json').read_text())
registry=json.loads(subprocess.check_output(['node','-e',"const E=require('./engine.js');console.log(JSON.stringify({moves:E.MOVES,skills:E.SKILLS}))"],cwd=ROOT))
records={r['id']:r for p in ROOT.glob('sources-*.json') for r in json.loads(p.read_text())}
assert set(review['entries'])==set(registry['moves']),'Every canonical movement needs an explicit instruction/coverage entry'
source_ids=set()
for id,entry in review['entries'].items():
 assert entry['coverage'] and entry['purpose']
 assert len(entry['videoSourceIds'])<=2 and set(entry['videoSourceIds'])<=set(entry['sourceIds'])
 for evidence in entry['evidence']:
  text=' '.join(records[evidence['sourceId']]['text'].split());assert evidence['quote'] in text,(id,evidence)
 for source in entry['sourceIds']:
  assert source in records
  assert re.fullmatch(r'https://www\.youtube\.com/watch\?v=[\w-]{11}',records[source]['url']),records[source]['url']
 source_ids.update(entry['sourceIds'])
for link in review['links']:
 assert link['from'] in registry['moves'] and link['to'] in registry['moves']
 assert link['dimension'] in ['complexity','combination'] and link['sourceIds']
 source_ids.update(link['sourceIds'])
for m in registry['moves'].values():source_ids.update(m.get('teachingSources',[]))
for s in registry['skills'].values():source_ids.update(s['sources'])
review['sources']={id:{'id':id,'title':records[id]['title'],'url':records[id]['url'],'sha256':hashlib.sha256(' '.join(records[id]['text'].split()).encode()).hexdigest(),'timestamps':None} for id in sorted(source_ids)}
js="/* Generated by scripts/build-learning.py from reviewed data and the verified corpus. */\n(function(root,value){if(typeof module==='object'&&module.exports)module.exports=value;else root.MovementInstruction=value;})(typeof globalThis!=='undefined'?globalThis:this,"+json.dumps(review,ensure_ascii=False,separators=(',',':'))+");\n"
(ROOT/'movement-instruction.js').write_text(js)
print(f"PASS: {len(review['entries'])} canonical instruction entries; {len(source_ids)} source mappings; exact quote/hash checks; no timestamps invented")
